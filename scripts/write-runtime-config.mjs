/**
 * Writes public/inkling-config.js from environment (used before static copy / Tauri build).
 */
import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const outPaths = [
  path.join(root, "public", "inkling-config.js"),
  path.join(root, "inkling-config.js")
];

const apiUrl = (process.env.INKLING_API_URL || process.env.VITE_INKLING_API_URL || "").trim();
const platform = (process.env.INKLING_PLATFORM || process.env.TAURI_ENV_PLATFORM || "web").trim();
// A unique, human-readable build stamp (UTC) so the in-app version readout
// changes every deploy and users can tell when an update landed.
function defaultBuildTag() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getUTCFullYear()}.${p(d.getUTCMonth() + 1)}.${p(d.getUTCDate())}.${p(d.getUTCHours())}${p(d.getUTCMinutes())}`;
}
const buildTag = (process.env.INKLING_BUILD_TAG || defaultBuildTag()).trim();
// Web Push: the VAPID public key the browser subscribes with. Safe to ship.
// Falls back to vapid-public.json (written by scripts/gen-vapid.mjs) so a normal
// build picks it up without needing the env var set.
let vapidPublicKey = (process.env.INKLING_VAPID_PUBLIC_KEY || process.env.VAPID_PUBLIC_KEY || "").trim();
if (!vapidPublicKey) {
  try {
    const raw = await fs.readFile(path.join(root, "vapid-public.json"), "utf8");
    vapidPublicKey = (JSON.parse(raw).publicKey || "").trim();
  } catch {
    /* no local key file — leave empty (push disabled) */
  }
}

const content = `/**
 * Generated by scripts/write-runtime-config.mjs — do not edit by hand.
 * @type {{ apiUrl: string, platform: string, buildTag: string }}
 */
window.__INKLING_RUNTIME__ = {
  apiUrl: ${JSON.stringify(apiUrl)},
  platform: ${JSON.stringify(platform)},
  buildTag: ${JSON.stringify(buildTag)},
  vapidPublicKey: ${JSON.stringify(vapidPublicKey)},
  nativeShell: ${JSON.stringify(platform === "android" || platform === "ios" || platform === "desktop")}
};

if (window.__INKLING_RUNTIME__.apiUrl) {
  window.__EUGENEOUS_API__ = window.__INKLING_RUNTIME__.apiUrl.replace(/\\/$/, "");
}
if (window.__INKLING_RUNTIME__.vapidPublicKey) {
  window.__INKLING_VAPID__ = window.__INKLING_RUNTIME__.vapidPublicKey;
}
`;

for (const outPath of outPaths) {
  await fs.mkdir(path.dirname(outPath), { recursive: true });
  await fs.writeFile(outPath, content, "utf8");
}
console.log(
  `[inkling-config] platform=${platform} apiUrl=${apiUrl || "(same-origin)"} → inkling-config.js`
);
